/**
 * The chain animation for the static decks (the Compute in Transit hub and
 * deck 04): src/lib/chain/model.ts and render.ts compiled to one plain
 * script, with the illustrative inputs and the byte counts (read from the
 * vendored results by src/lib/chain/bytes.ts) embedded. The decks inline
 * it, so the site and the decks draw the same frames from the same code.
 *
 *   pnpm exec tsx scripts/build-chain-js.ts <out.js>
 *
 * It exposes window.CitChain = { chainRun, chainStages, diagramSvg,
 * viewSvg, bytesSvg, legendSvg, blockLabel, BLOCKS, TAG, INPUTS, BYTES }.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import ts from "typescript";

import { chainBytes } from "../src/lib/chain/bytes";
import { chainInputs } from "../src/lib/data/load";

const out = process.argv[2];
if (!out) throw new Error("usage: tsx scripts/build-chain-js.ts <out.js>");

function strip(file: string): string {
  const src = readFileSync(join(process.cwd(), file), "utf8");
  const js = ts.transpileModule(src, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2019,
      module: ts.ModuleKind.ESNext,
      removeComments: false,
    },
  }).outputText;
  return js
    .replace(/^import[^;]*;\s*$/gm, "")
    .replace(/^export \{\};?\s*$/gm, "")
    .replace(/^export (function|const|let)/gm, "$1");
}

const model = strip("src/lib/chain/model.ts");
const render = strip("src/lib/chain/render.ts");
const hash = createHash("sha256")
  .update(readFileSync("src/lib/chain/model.ts"))
  .update(readFileSync("src/lib/chain/render.ts"))
  .digest("hex")
  .slice(0, 12);
const body = `// Generated by compute-in-transit-results/scripts/build-chain-js.ts from src/lib/chain/model.ts and render.ts
// (sources sha256 ${hash}). Do not edit: change the sources and regenerate. MIT licence.
(function () {
"use strict";
${model}
${render}
const INPUTS = ${JSON.stringify(chainInputs())};
const BYTES = ${JSON.stringify(chainBytes())};
window.CitChain = { chainRun, chainStages, diagramSvg, viewSvg, bytesSvg, legendSvg, blockLabel, BLOCKS, TAG, INPUTS, BYTES };
})();
`;
writeFileSync(out, body);
console.log(
  `wrote ${out} (${Math.round(body.length / 1024)} KB, sources ${hash})`,
);
